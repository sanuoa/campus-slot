CREATE TABLE campus_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('STUDENT', 'ADMIN')),
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT iit_email CHECK (email = lower(email) AND email ~ '^[a-z0-9._%+\-]+@iit\.ac\.lk$')
);
CREATE TABLE verification_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES campus_user(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE facility (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(24) NOT NULL CHECK (type IN ('STUDY_ROOM','COMPUTER_LAB','SPORTS_COURT')),
    location VARCHAR(160) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE facility_slot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id BIGINT NOT NULL REFERENCES facility(id),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    blocked BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (facility_id, starts_at),
    CHECK (ends_at = starts_at + INTERVAL '1 hour'),
    CHECK (EXTRACT(MINUTE FROM starts_at AT TIME ZONE 'Asia/Colombo') = 0),
    CHECK (EXTRACT(SECOND FROM starts_at AT TIME ZONE 'Asia/Colombo') = 0)
);
CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES campus_user(id),
    slot_id BIGINT NOT NULL REFERENCES facility_slot(id),
    booking_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Completed bookings remain CONFIRMED in storage; COMPLETED is derived from the end time.
-- A completed session still consumes the student's quota for that Sri Lanka date.
CREATE UNIQUE INDEX one_booking_per_slot ON booking(slot_id) WHERE status = 'CONFIRMED';
CREATE UNIQUE INDEX one_hour_per_student_per_day ON booking(user_id, booking_date) WHERE status = 'CONFIRMED';
CREATE INDEX slots_by_time ON facility_slot(starts_at);
